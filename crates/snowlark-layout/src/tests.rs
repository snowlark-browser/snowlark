/// A text engine with Ahem registered (the WPT font, public domain); returns it and Ahem's family name.
pub(crate) fn engine() -> (TextEngine, String) {
    let e = TextEngine::new().expect("DirectWrite");
    let ahem = e
        .add_font_data(include_bytes!("../tests/fixtures/Ahem.ttf"))
        .expect("Ahem");
    (e, ahem)
}

pub(crate) type F = Arc<Fragment<Arc<TestStyle>>>;

pub(crate) struct T {
    pub doc: TestDocument,
    pub text: TextEngine,
    pub layout: LayoutTree<Arc<TestStyle>>,
    pub viewport: Size,
}

impl T {
    /// A document whose root uses Ahem at 10px with `line-height: 1`.
    pub fn new() -> T {
        let (text, ahem) = engine();
        let doc = TestDocument::with_root_style(move |s| {
            s.display = Display::BLOCK;
            s.font_family = vec![ahem];
            s.font_size = 10.0;
            s.line_height = LineHeight::Number(1.0);
        });
        T {
            doc,
            text,
            layout: LayoutTree::new(),
            viewport: Size::new(800.0, 600.0),
        }
    }

    pub fn root(&self) -> NodeId {
        self.doc.root
    }

    /// Builds the box tree and lays out in a `width` × `height` viewport.
    pub fn run(&mut self, width: f32, height: f32) -> F {
        self.viewport = Size::new(width, height);
        self.layout
            .build(&self.doc.dom, self.doc.document, &self.doc.styles);
        self.layout.layout(&self.text, self.viewport)
    }

    pub fn relayout(&mut self) -> F {
        self.layout.layout(&self.text, self.viewport)
    }

    pub fn dump(&self) -> String {
        self.layout.boxes().dump()
    }
}

/// The border box of the first fragment generated by `node`.
pub(crate) fn rect(f: &F, node: NodeId) -> Rect {
    let (at, fr) = f
        .find(node)
        .unwrap_or_else(|| panic!("no fragment for {node:?}\n{}", f.dump()));
    Rect::new(at.x, at.y, fr.size.width, fr.size.height)
}

/// The rects of the line boxes inside `node`'s fragment (absolute).
pub(crate) fn lines(f: &F, node: NodeId) -> Vec<Rect> {
    let (at, fr) = f.find(node).expect("fragment");
    let mut out = Vec::new();
    for c in &fr.children {
        if let FragmentKind::Line { .. } = c.fragment.kind {
            if c.fragment.size.height > 0.0 {
                out.push(Rect::new(
                    at.x + c.offset.x,
                    at.y + c.offset.y,
                    c.fragment.size.width,
                    c.fragment.size.height,
                ));
            }
        }
    }
    out
}

/// The rects of the text fragments of a text node (absolute).
pub(crate) fn texts(f: &F, node: NodeId) -> Vec<Rect> {
    let mut out = Vec::new();
    f.walk(&mut |fr, at| {
        if let FragmentKind::Text(t) = &fr.kind {
            if t.node == Some(node) {
                out.push(Rect::new(at.x, at.y, fr.size.width, fr.size.height));
            }
        }
    });
    out
}

pub(crate) fn r(x: f32, y: f32, w: f32, h: f32) -> Rect {
    Rect::new(x, y, w, h)
}

