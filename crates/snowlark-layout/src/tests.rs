/// CSS Text 3 §6.1: a line that breaks at a soft hyphen ends with the hyphenation character, which
/// must fit too; `hyphens: none` takes the soft hyphen's wrap opportunity away.
#[test]
fn soft_hyphens_break_with_a_hyphen() {
    let mut t = T::new();
    let r0 = t.root();
    let mut block = |width: f32, hyphens: Hyphens, character: Option<&str>| {
        let b = t.doc.block(r0, |s| {
            s.width = SizeValue::px(width);
            s.hyphens = hyphens;
            s.hyphenate_character = character.map(str::to_string);
        });
        let text = t.doc.text(b, "aaa\u{AD}bbb");
        (b, text)
    };
    let (manual, manual_text) = block(45.0, Hyphens::Manual, None);
    let (auto, _) = block(55.0, Hyphens::Auto, Some("=="));
    let (none, none_text) = block(45.0, Hyphens::None, None);
    // "aaa" and its hyphen are 40px: no room in 35px.
    let (narrow, _) = block(35.0, Hyphens::Manual, None);
    let f = t.run(400.0, 600.0);
    // The hyphens: visible text fragments that stand for the soft hyphen (bytes 3..5) alone.
    let hyphens_in = |b| {
        let at = rect(&f, b);
        let mut out = Vec::new();
        f.walk(&mut |fr, p| {
            if let FragmentKind::Text(t) = &fr.kind {
                let here = p.y >= at.y && p.y < at.y + at.height;
                if t.text_range == (3..5) && fr.size.width > 0.0 && here {
                    out.push(r(p.x - at.x, p.y - at.y, fr.size.width, fr.size.height));
                }
            }
        });
        out
    };
    // The soft hyphen itself is invisible: "aaabbb" is 60px on one line.
    let widths: f32 = texts(&f, none_text).iter().map(|t| t.width).sum();
    assert_eq!(widths, 60.0);
    assert_eq!(rect(&f, manual).height, 20.0);
    assert_eq!(hyphens_in(manual), vec![r(30.0, 0.0, 10.0, 10.0)]);
    // A range over the soft hyphen covers the hyphen (CSSOM View: the hyphen is its text's).
    let width = |a, b| -> f32 {
        t.layout
            .text_range_rects(manual_text, a, b)
            .iter()
            .map(|r| r.width)
            .sum()
    };
    assert_eq!(width(0, 3), 30.0);
    assert_eq!(width(0, 5), 40.0);
    assert_eq!(width(3, 5), 10.0);
    assert_eq!(rect(&f, auto).height, 20.0);
    assert_eq!(hyphens_in(auto), vec![r(30.0, 0.0, 20.0, 10.0)]);
    assert_eq!(rect(&f, none).height, 10.0);
    assert!(hyphens_in(none).is_empty());
    assert_eq!(rect(&f, narrow).height, 10.0);
    assert!(hyphens_in(narrow).is_empty());
}

