/// CSS Text 3 §5: between two atomic inlines, the `white-space` of their nearest common ancestor
/// decides whether the line may wrap, not the boxes' own (which applies inside them): inline-blocks
/// that wrap their text stay on one line in a `nowrap` parent, and `nowrap` ones wrap in a parent
/// that wraps.
#[test]
fn wrapping_between_atomic_inlines_follows_their_parent() {
    let mut t = T::new();
    let r0 = t.root();
    let mut row = |parent_mode: TextWrapMode, own_mode: TextWrapMode| {
        let p = t.doc.block(r0, |s| {
            s.width = SizeValue::px(30.0);
            s.text_wrap_mode = parent_mode;
        });
        let items: Vec<_> = (0..3)
            .map(|_| {
                t.doc.element(p, "span", |s| {
                    s.display = Display::INLINE_BLOCK;
                    s.width = SizeValue::px(20.0);
                    s.height = SizeValue::px(10.0);
                    s.text_wrap_mode = own_mode;
                })
            })
            .collect();
        (p, items)
    };
    let (nowrap, kept) = row(TextWrapMode::Nowrap, TextWrapMode::Wrap);
    let (wrap, wrapped) = row(TextWrapMode::Wrap, TextWrapMode::Nowrap);
    let f = t.run(200.0, 200.0);
    let ys = |items: &[_]| items.iter().map(|&i| rect(&f, i).y).collect::<Vec<_>>();
    let top = rect(&f, nowrap).y;
    assert_eq!(ys(&kept), vec![top; 3], "one line in the nowrap parent");
    let top = rect(&f, wrap).y;
    let wrapped_ys = ys(&wrapped);
    assert!(
        wrapped_ys[0] == top && wrapped_ys[1] > top && wrapped_ys[2] > wrapped_ys[1],
        "a line each in the parent that wraps: {wrapped_ys:?}"
    );
}

