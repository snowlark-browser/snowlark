//! Layout tests: expected geometry for each algorithm (cases from CSS 2's examples and from the WPT css
//! suites' `check-layout-th` expectations, transcribed into trees), using the Ahem font so text has exact
//! metrics: every glyph is an em square, ascent 0.8em, descent 0.2em. The root is Ahem 10px with
//! `line-height: 1`, so a line of text is 10px tall and each character 10px wide.

use std::sync::Arc;

