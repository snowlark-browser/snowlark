/// CSS Text 3 §4.1.3: `pre-wrap`'s spaces at a line end hang, so they do not count in the
/// min-content size (they stay in the max-content size); `break-spaces` keeps them and has a wrap
/// opportunity after every space (§5.1).
#[test]
fn hanging_preserved_spaces_in_min_content() {
    let mut t = T::new();
    let r0 = t.root();
    let narrow = t.doc.block(r0, |s| s.width = SizeValue::px(0.0));
    let wide = t.doc.block(r0, |_| {});
    let cases = [
        (WhiteSpaceCollapse::Preserve, " ", 0.0),
        (WhiteSpaceCollapse::Preserve, "  ", 0.0),
        (WhiteSpaceCollapse::Preserve, "  X", 10.0),
        (WhiteSpaceCollapse::Preserve, "X  XX ", 20.0),
        (WhiteSpaceCollapse::BreakSpaces, "  ", 10.0),
        // (no wrap opportunity before a space: "X " stays together)
        (WhiteSpaceCollapse::BreakSpaces, "X  ", 20.0),
        // (no wrap opportunity after a no-break space)
        (WhiteSpaceCollapse::BreakSpaces, "X\u{A0}X", 30.0),
    ];
    let max_cases = [
        (WhiteSpaceCollapse::Preserve, " ", 10.0),
        (WhiteSpaceCollapse::Preserve, "X  ", 30.0),
        (WhiteSpaceCollapse::BreakSpaces, "  ", 20.0),
        (WhiteSpaceCollapse::Collapse, "X  ", 10.0),
    ];
    let nodes: Vec<_> = cases
        .iter()
        .map(|&(c, x, w)| (narrow, c, x, w))
        .chain(max_cases.iter().map(|&(c, x, w)| (wide, c, x, w)))
        .map(|(parent, collapse, text, want)| {
            let ib = t.doc.element(parent, "span", |s| {
                s.display = Display::INLINE_BLOCK;
                s.white_space_collapse = collapse;
            });
            t.doc.text(ib, text);
            (ib, collapse, text, want)
        })
        .collect();
    let f = t.run(400.0, 600.0);
    for (node, collapse, text, want) in nodes {
        assert_eq!(rect(&f, node).width, want, "{collapse:?} {text:?}");
    }
}

