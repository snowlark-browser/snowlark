#[test]
fn text_flows_around_a_float() {
    let mut t = T::new();
    let r0 = t.root();
    let p = t.doc.block(r0, |s| s.width = SizeValue::px(100.0));
    let fl = t.doc.block(p, |s| {
        s.float = Float::Left;
        s.width = SizeValue::px(30.0);
        s.height = SizeValue::px(25.0);
    });
    let text = t.doc.text(p, "aaa bbb ccc ddd eee fff ggg");
    let f = t.run(200.0, 200.0);
    assert_eq!(rect(&f, fl), r(0.0, 0.0, 30.0, 25.0));
    let ls = lines(&f, p);
    // Beside the float: 70px of room, "aaa bbb" (70px) fits; below it at y=30 the full width.
    assert_eq!(ls[0], r(30.0, 0.0, 70.0, 10.0));
    assert_eq!(ls[2], r(30.0, 20.0, 70.0, 10.0));
    assert_eq!(ls[3].x, 0.0);
    let tx = texts(&f, text);
    assert_eq!(tx[0], r(30.0, 0.0, 70.0, 10.0));
    // the paragraph's height doesn't include the float
    assert_eq!(rect(&f, p).height, 40.0);
}

#[test]
fn text_wraps_around_a_floats_shape() {
    // CSS Shapes 1 §3: a triangle `polygon(0 0, 100% 0, 0 100%)` on a 100px float: each 10px
    // line starts where the triangle's edge is at the line's bottom (the line is fitted again at
    // its own height), and the margin box does not count.
    let text = "aaa bbb ccc ddd eee fff ggg hhh iii jjj kkk lll mmm nnn ooo ppp";
    let run = |shape: Option<ShapeOutside>| {
        let mut t = T::new();
        let r0 = t.root();
        let p = t.doc.block(r0, |s| s.width = SizeValue::px(200.0));
        t.doc.block(p, |s| {
            s.float = Float::Left;
            s.width = SizeValue::px(100.0);
            s.height = SizeValue::px(100.0);
            s.shape_outside = shape.clone();
        });
        t.doc.text(p, text);
        let f = t.run(300.0, 300.0);
        lines(&f, p).iter().map(|l| l.x).collect::<Vec<f32>>()
    };
    let pct = LengthPercentage::percent;
    let triangle = ShapeOutside::Shape(
        ClipShape::Polygon {
            even_odd: false,
            points: vec![
                (pct(0.0), pct(0.0)),
                (pct(100.0), pct(0.0)),
                (pct(0.0), pct(100.0)),
            ],
        },
        ClipBox::Margin,
    );
    assert_eq!(run(Some(triangle))[..3], [100.0, 90.0, 80.0]);
    // with no shape, every line beside the float starts at its margin box
    assert_eq!(run(None)[..3], [100.0, 100.0, 100.0]);
}

