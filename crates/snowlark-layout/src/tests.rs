#[test]
fn text_change_relayout_reuses_clean_subtrees() {
    let mut t = T::new();
    let r0 = t.root();
    let mut texts_nodes = Vec::new();
    for i in 0..20 {
        let p = t.doc.block(r0, |_| {});
        texts_nodes.push(t.doc.text(p, &format!("paragraph {i} text")));
    }
    let first = t.run(300.0, 300.0);
    let full = t.layout.stats();
    t.doc.dom.set_data(
        texts_nodes[5],
        "changed text that is much longer than before and wraps",
    );
    assert!(t.layout.text_changed(&t.doc.dom, texts_nodes[5]));
    let second = t.relayout();
    let inc = t.layout.stats();
    assert!(inc.laid_out < 5, "{inc:?} vs {full:?}");
    assert!(inc.reused >= 19, "{inc:?}");
    assert_eq!(inc.shaped, 1);
    // Unchanged paragraphs above keep the very same fragments.
    let p0 = |f: &F| f.children[0].fragment.children[0].fragment.clone();
    assert!(Arc::ptr_eq(&p0(&first), &p0(&second)));
    // ...and the result equals a full layout.
    let mut fresh = T::new();
    let r1 = fresh.root();
    for i in 0..20 {
        let p = fresh.doc.block(r1, |_| {});
        let s = if i == 5 {
            "changed text that is much longer than before and wraps".to_string()
        } else {
            format!("paragraph {i} text")
        };
        fresh.doc.text(p, &s);
    }
    let full_again = fresh.run(300.0, 300.0);
    assert_eq!(second.dump(), full_again.dump());
}

