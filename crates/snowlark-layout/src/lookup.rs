//! Finding a node's fragments in the last fragment tree, for script reads (CSSOM View §6
//! `getClientRects()`/`getBoundingClientRect()`, §7 `offset*`, CSSOM §6.7.2 used values) and hit
//! testing results.
//!
//! A read asks for one node's boxes; walking the whole fragment tree per read made a script that
//! reads every element quadratic. Two ways instead:
//! - a guided search: the fragments a node generates nest only in fragments generated by the node's
//!   box tree ancestors (its containing blocks are among them, the initial containing block's being
//!   the root fragment) and in anonymous fragments (line boxes, anonymous boxes), so the search
//!   enters only those: its cost is the fragments along the node's path and their children, not
//!   the tree.
//! - an index from node to fragments over the whole tree, built once the guided searches since the
//!   last layout have visited as many fragments as the tree holds boxes. A burst of reads with no
//!   change in between then costs O(1) each, and a read after each change (the index would be
//!   rebuilt per layout) costs only its path.
//!
//! Both come in two kinds of placement: each fragment's offset in the root fragment, and, for reads
//! that apply transforms (`getClientRects()` under a transformed box), the matrix from the fragment
//! to the root composed along the same path. That is how Blink maps a box to the viewport:
//! `LayoutObject::MapLocalToAncestor` (layout_object.cc) climbs the container chain and applies each
//! container's transform (`GetTransformFromContainer`), at the cost of the box's depth, not of the
//! tree; `Element::ClientQuads` (element.cc, through `LocalToAbsoluteQuad`) and the target rectangle
//! of `IntersectionGeometry` (intersection_geometry.cc) both go through it.

use std::sync::atomic::{AtomicUsize, Ordering};
use std::sync::{Arc, Mutex};

use rustc_hash::{FxHashMap, FxHashSet};
use smallvec::SmallVec;
use snowlark_dom::NodeId;
use snowlark_paint::{Matrix, Point};

use crate::fragment::{Fragment, FragmentChild};
use crate::style::{PseudoElement, Style};

/// Where a fragment is, in the root fragment's coordinates.
pub(crate) trait Place: Copy + PartialEq + std::fmt::Debug {
    /// The root fragment's placement.
    const ROOT: Self;
    /// The placement of `child` of a fragment placed at `self`.
    fn child<S: Style>(self, child: &FragmentChild<S>) -> Self;
}

impl Place for Point {
    const ROOT: Self = Point::ZERO;
    fn child<S: Style>(self, c: &FragmentChild<S>) -> Self {
        Point::new(self.x + c.offset.x, self.y + c.offset.y)
    }
}

/// A placement with transforms: the matrix from the fragment's own border-box coordinates (its own
/// transform included) to the root fragment's.
#[derive(Clone, Copy, Debug, PartialEq)]
pub(crate) struct Transformed {
    pub m: Matrix,
    /// Whether a transform is on the way (else `m` is a translation, and is applied as one).
    pub any: bool,
}

impl Place for Transformed {
    const ROOT: Self = Transformed {
        m: Matrix::IDENTITY,
        any: false,
    };
    fn child<S: Style>(self, c: &FragmentChild<S>) -> Self {
        let offset = Matrix::translation(c.offset.x, c.offset.y);
        match c
            .fragment
            .as_box()
            .and_then(|b| b.used_transform(c.fragment.size))
        {
            Some(t) => Transformed {
                m: t.then(&offset).then(&self.m),
                any: true,
            },
            None => Transformed {
                m: offset.then(&self.m),
                any: self.any,
            },
        }
    }
}

type Entries<S, P> = SmallVec<[(P, Arc<Fragment<S>>); 1]>;

/// The lookup state of one fragment tree (reset by each layout that produces a new tree).
pub(crate) struct Lookup<S: Style> {
    offsets: Mutex<State<S, Point>>,
    transformed: Mutex<State<S, Transformed>>,
    /// The fragments the reads since the tree was made visited (searches, index builds and the
    /// walks passed to [`Lookup::count`]): what reads cost, for tests.
    searched: AtomicUsize,
}

struct State<S: Style, P: Place> {
    /// The fragments the guided searches visited since the tree was made.
    visited: usize,
    index: Option<FxHashMap<NodeId, Entries<S, P>>>,
}

impl<S: Style, P: Place> Default for State<S, P> {
    fn default() -> Self {
        State {
            visited: 0,
            index: None,
        }
    }
}

impl<S: Style> Default for Lookup<S> {
    fn default() -> Self {
        Lookup {
            offsets: Mutex::default(),
            transformed: Mutex::default(),
            searched: AtomicUsize::new(0),
        }
    }
}

/// Whether `f` is a `::backdrop` box (it carries its element's node for hit testing, but is not
/// one of the element's boxes).
pub(crate) fn is_backdrop<S: Style>(f: &Fragment<S>) -> bool {
    f.as_box()
        .is_some_and(|b| b.pseudo == Some(PseudoElement::Backdrop))
}

impl<S: Style> Lookup<S> {
    /// A new tree was laid out: what was known about the old one goes.
    pub(crate) fn reset(&mut self) {
        *self.offsets.get_mut().unwrap_or_else(|e| e.into_inner()) = State::default();
        *self
            .transformed
            .get_mut()
            .unwrap_or_else(|e| e.into_inner()) = State::default();
        *self.searched.get_mut() = 0;
    }

    /// The fragments the reads since the tree was made visited.
    pub(crate) fn searched(&self) -> usize {
        self.searched.load(Ordering::Relaxed)
    }

    /// Counts `n` fragments a read visited outside the lookup (a walk of the whole tree).
    pub(crate) fn count(&self, n: usize) {
        self.searched.fetch_add(n, Ordering::Relaxed);
    }

    /// Runs `f` with the fragments `node` generated in `root` (tree order, each with its offset in
    /// the root fragment's coordinates). `ancestors` gives the nodes of the box tree ancestors of the
    /// node's principal box (`None`: the node has no box, so no fragments); `boxes` is the number of
    /// boxes in the tree.
    pub(crate) fn with<R>(
        &self,
        root: &Arc<Fragment<S>>,
        node: NodeId,
        ancestors: impl FnOnce() -> Option<FxHashSet<NodeId>>,
        boxes: usize,
        f: impl FnOnce(&[(Point, &Fragment<S>)]) -> R,
    ) -> R {
        self.find(&self.offsets, root, node, ancestors, boxes, f)
    }

    /// [`Lookup::with`], each fragment with the matrix from its own coordinates to the root
    /// fragment's (its transform and those of the fragments it is in applied).
    pub(crate) fn with_transformed<R>(
        &self,
        root: &Arc<Fragment<S>>,
        node: NodeId,
        ancestors: impl FnOnce() -> Option<FxHashSet<NodeId>>,
        boxes: usize,
        f: impl FnOnce(&[(Transformed, &Fragment<S>)]) -> R,
    ) -> R {
        self.find(&self.transformed, root, node, ancestors, boxes, f)
    }

    fn find<P: Place, R>(
        &self,
        state: &Mutex<State<S, P>>,
        root: &Arc<Fragment<S>>,
        node: NodeId,
        ancestors: impl FnOnce() -> Option<FxHashSet<NodeId>>,
        boxes: usize,
        f: impl FnOnce(&[(P, &Fragment<S>)]) -> R,
    ) -> R {
        let mut st = state.lock().unwrap_or_else(|e| e.into_inner());
        if st.index.is_none() && st.visited >= boxes.max(64) {
            let mut built = 0;
            st.index = Some(build_index(root, &mut built));
            self.count(built);
        }
        if let Some(index) = &st.index {
            let found: SmallVec<[(P, &Fragment<S>); 4]> = index
                .get(&node)
                .map(|e| e.iter().map(|(p, fr)| (*p, &**fr)).collect())
                .unwrap_or_default();
            return f(&found);
        }
        let Some(ancestors) = ancestors() else {
            return f(&[]);
        };
        let mut found: SmallVec<[(P, &Fragment<S>); 4]> = SmallVec::new();
        let mut visited = 0;
        search(root, P::ROOT, node, &ancestors, &mut found, &mut visited);
        st.visited += visited;
        drop(st);
        self.count(visited);
        #[cfg(debug_assertions)]
        {
            fn all<S: Style, P: Place>(
                fr: &Fragment<S>,
                at: P,
                node: NodeId,
                out: &mut Vec<(P, *const Fragment<S>)>,
            ) {
                if fr.node() == Some(node) {
                    out.push((at, fr as *const Fragment<S>));
                }
                for c in &fr.children {
                    all(&c.fragment, at.child(c), node, out);
                }
            }
            let mut every = Vec::new();
            all(root, P::ROOT, node, &mut every);
            let got: Vec<_> = found
                .iter()
                .map(|(p, fr)| (*p, *fr as *const Fragment<S>))
                .collect();
            debug_assert_eq!(
                got, every,
                "guided fragment search missed fragments of {node:?}"
            );
        }
        f(&found)
    }
}

/// The guided search from `fr` at `at`.
fn search<'a, S: Style, P: Place>(
    fr: &'a Fragment<S>,
    at: P,
    node: NodeId,
    ancestors: &FxHashSet<NodeId>,
    out: &mut SmallVec<[(P, &'a Fragment<S>); 4]>,
    visited: &mut usize,
) {
    *visited += 1;
    if fr.node() == Some(node) {
        out.push((at, fr));
    }
    for c in &fr.children {
        let enter = match c.fragment.node() {
            None => true,
            Some(n) => n == node || ancestors.contains(&n),
        };
        if enter {
            search(&c.fragment, at.child(c), node, ancestors, out, visited);
        } else {
            *visited += 1;
        }
    }
}

fn build_index<S: Style, P: Place>(
    root: &Arc<Fragment<S>>,
    visited: &mut usize,
) -> FxHashMap<NodeId, Entries<S, P>> {
    fn go<S: Style, P: Place>(
        fr: &Arc<Fragment<S>>,
        at: P,
        out: &mut FxHashMap<NodeId, Entries<S, P>>,
        visited: &mut usize,
    ) {
        *visited += 1;
        if let Some(n) = fr.node() {
            out.entry(n).or_default().push((at, fr.clone()));
        }
        for c in &fr.children {
            go(&c.fragment, at.child(c), out, visited);
        }
    }
    let mut out = FxHashMap::default();
    go(root, P::ROOT, &mut out, visited);
    out
}
