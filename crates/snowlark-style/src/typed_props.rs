/// The kinds of value `property` takes; `None` when no subclass represents its values.
pub fn types(property: &str) -> Option<u16> {
    TYPES
        .binary_search_by(|(name, _)| (*name).cmp(property))
        .ok()
        .map(|i| TYPES[i].1)
}
