//! Where the fields the player reads lie in FFmpeg's structures, per release: the libraries are the
//! system's, loaded at run time, so their layout is the one of whichever release is installed. The
//! entries are printed by `tools/ffmpeg/layout.sh` from each release's headers (6.1, 7.1, 8.0).

/// One FFmpeg release's library versions (the majors in their file names) and field offsets.
#[allow(non_snake_case)]
#[derive(Debug)]
pub struct Layout {
    pub avcodec: u32,
    pub avformat: u32,
    pub avutil: u32,
    pub swscale: u32,
    pub swresample: u32,
    pub AVFormatContext_pb: usize,
    pub AVFormatContext_nb_streams: usize,
    pub AVFormatContext_streams: usize,
    pub AVFormatContext_start_time: usize,
    pub AVFormatContext_duration: usize,
    pub AVStream_codecpar: usize,
    pub AVStream_time_base: usize,
    pub AVStream_start_time: usize,
    pub AVStream_duration: usize,
    pub AVCodecParameters_codec_type: usize,
    pub AVCodecParameters_codec_id: usize,
    pub AVCodecParameters_format: usize,
    pub AVCodecParameters_width: usize,
    pub AVCodecParameters_height: usize,
    pub AVCodecParameters_sample_rate: usize,
    pub AVCodecParameters_ch_layout: usize,
    pub AVPacket_data: usize,
    pub AVPacket_size: usize,
    pub AVPacket_stream_index: usize,
    pub AVPacket_flags: usize,
    pub AVPacket_pts: usize,
    pub AVPacket_dts: usize,
    pub AVPacket_duration: usize,
    pub AVFrame_data: usize,
    pub AVFrame_linesize: usize,
    pub AVFrame_extended_data: usize,
    pub AVFrame_width: usize,
    pub AVFrame_height: usize,
    pub AVFrame_nb_samples: usize,
    pub AVFrame_format: usize,
    pub AVFrame_pts: usize,
    pub AVFrame_best_effort_timestamp: usize,
    pub AVFrame_sample_rate: usize,
    pub AVFrame_ch_layout: usize,
}

