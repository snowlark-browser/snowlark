//! The V8 bindings generator: plans the generated set from the linked model, then writes one file per
//! interface and mixin, `types.rs`, `mod.rs` (ids, the `Dom` trait, `install`) and `OMITTED.txt`.

mod conv;
mod iface;
pub mod names;
pub mod plan;
mod types;

use crate::ast::Literal;
use names::*;
use plan::*;
use std::collections::BTreeMap;
use std::fmt::Write;
use types::HEADER;

/// The generated files, by path relative to `crates/snowlark-bindings/src/generated/`.
pub fn generate(model: &crate::model::Model, enumerated_src: &str) -> BTreeMap<String, String> {
    let enumerated = parse_enumerated(enumerated_src);
    let mut plan = Plan::new(model, &enumerated);
    plan.inherit_specials();
    let mut files = BTreeMap::new();
    files.insert("types.rs".to_string(), plan.emit_types());
    for owner in plan.traits.keys() {
        files.insert(
            format!("{}.rs", plan.traits[owner].file),
            plan.emit_owner(owner),
        );
    }
    files.insert("mod.rs".to_string(), plan.emit_mod());
    let mut omitted: Vec<String> = plan.omitted.clone();
    omitted.sort();
    omitted.dedup();
    let mut text = String::from(
        "# Members of the generated interfaces left out of the bindings, and why. Generated by snowlark-idl;\n# shrinks as interfaces join the generated set.\n\n",
    );
    for line in &omitted {
        text.push_str(line);
        text.push('\n');
    }
    files.insert("OMITTED.txt".to_string(), text);
    files
}

impl Plan<'_> {
    /// Interfaces that inherit an indexed or named property handler get it on their own instance
    /// template too, so derived wrappers keep legacy platform object behavior.
    fn inherit_specials(&mut self) {
        let by_name: BTreeMap<String, usize> = self
            .ifaces
            .iter()
            .enumerate()
            .map(|(i, p)| (p.name.clone(), i))
            .collect();
        for i in 0..self.ifaces.len() {
            let Some(parent) = self.ifaces[i].parent.clone() else {
                continue;
            };
            let p = self.ifaces[by_name[&parent]].clone();
            let me = &mut self.ifaces[i];
            if me.indexed_getter.is_none() {
                me.indexed_getter = p.indexed_getter.clone();
                if me.indexed_setter.is_none() {
                    me.indexed_setter = p.indexed_setter.clone();
                }
            }
            if me.named_getter.is_none() {
                me.named_getter = p.named_getter.clone();
                if me.named_setter.is_none() {
                    me.named_setter = p.named_setter.clone();
                }
                if me.named_deleter.is_none() {
                    me.named_deleter = p.named_deleter.clone();
                }
            }
            me.override_builtins |= p.override_builtins;
            me.unenumerable_named |= p.unenumerable_named;
        }
    }

    fn emit_mod(&self) -> String {
        let mut o = String::new();
        o.push_str(HEADER);
        o.push_str("//! The generated bindings: one module per interface and mixin with the trait the engine implements\n//! and the V8 callbacks, `types` for dictionaries, enumerations, unions and callbacks, the prototype ids,\n//! and `install`.\n\n");
        o.push_str("use crate::rt;\nuse std::rc::Rc;\n\n");
        o.push_str("pub mod types;\npub use types::*;\n");
        for t in self.traits.values() {
            writeln!(
                o,
                "pub mod {};\npub use {}::{};",
                t.file, t.file, t.trait_name
            )
            .unwrap();
        }
        o.push('\n');

        // Prototype ids.
        o.push_str("/// Prototype ids: depth-first over the inheritance tree, so an interface's descendants are\n/// `ids::X..ids::X_END`.\npub mod ids {\n");
        for ip in &self.ifaces {
            let id = upper(&ip.name);
            writeln!(
                o,
                "    pub const {id}: u16 = {};\n    pub const {id}_END: u16 = {};",
                ip.lo, ip.hi
            )
            .unwrap();
        }
        writeln!(
            o,
            "    /// The number of generated interfaces.\n    pub const COUNT: usize = {};\n}}\n",
            self.ifaces.len()
        )
        .unwrap();

        o.push_str("/// The generated interfaces; the engine names an object's most derived one in `Host::interface_of`.\n#[repr(u16)]\n#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]\n#[allow(non_camel_case_types)] // (WebGL extensions: `EXT_sRGB`)\npub enum InterfaceId {\n");
        for ip in &self.ifaces {
            writeln!(o, "    {} = {},", ip.name, ip.lo).unwrap();
        }
        o.push_str("}\n\nimpl InterfaceId {\n    pub fn name(self) -> &'static str {\n        match self {\n");
        for ip in &self.ifaces {
            writeln!(
                o,
                "            InterfaceId::{0} => {1},",
                ip.name,
                lit(&ip.name)
            )
            .unwrap();
        }
        o.push_str("        }\n    }\n}\n\n");

        // The Dom trait.
        let bounds: Vec<String> = std::iter::once("'static".to_string())
            .chain([
                "rt::Host".to_string(),
                "rt::Reflect".to_string(),
                "rt::EventHandlers".to_string(),
            ])
            .chain(self.traits.values().map(|t| t.trait_name.clone()))
            .collect();
        o.push_str("/// Everything the engine implements for the bindings: the hooks and one trait per generated interface\n/// and mixin. Implemented automatically for any type that implements them all.\npub trait Dom:\n");
        writeln!(o, "    {}\n{{\n}}\n", bounds.join("\n    + ")).unwrap();
        writeln!(
            o,
            "impl<T> Dom for T where T: {} {{}}\n",
            bounds.join(" + ")
        )
        .unwrap();

        o.push_str("/// Calls `$m!(Trait)` for every generated trait (for test mocks that stub most of them).\n#[macro_export]\nmacro_rules! for_each_trait {\n    ($m:ident) => {\n");
        for t in self.traits.values() {
            writeln!(o, "        $m!({});", t.trait_name).unwrap();
        }
        o.push_str("    };\n}\n\n");

        o.push_str("fn interface_of<D: Dom>(engine: &dyn std::any::Any, handle: rt::Handle) -> u16 {\n    let dom = engine.downcast_ref::<D>().expect(\"engine type\");\n    <D as rt::Host>::interface_of(dom, handle) as u16\n}\n\n");
        o.push_str("fn dom_exception<'s, D: Dom>(scope: &mut v8::PinScope<'s, '_>, message: &str, name: &str) -> Option<v8::Local<'s, v8::Value>> {\n    let st = rt::state(scope);\n    let dom = st.engine::<D>();\n    let h = { let mut cx = rt::Cx::new(scope); <D as DOMExceptionImpl>::constructor(dom, &mut cx, message, name) }.ok()?;\n    Some(rt::wrap(scope, h)?.into())\n}\n\n");

        // init_isolate: the templates.
        o.push_str("/// Builds every interface template in the isolate of `scope` and keeps `engine` for the callbacks.\n/// Templates belong to the isolate: every realm (context) made afterwards shares them. `scope` needs a\n/// context only because V8's Fast API template builder asks for one; any context will do.\npub fn init_isolate<D: Dom>(scope: &mut v8::PinScope<'_, '_>, engine: Rc<D>, options: rt::InstallOptions) -> Rc<rt::State> {\n");
        o.push_str("    let st = rt::set_state(scope, rt::State::new(engine, interface_of::<D>, dom_exception::<D>, ids::COUNT, options));\n");
        for ip in &self.ifaces {
            let parent = match &ip.parent {
                Some(p) => format!("Some(t_{})", self.traits[p].file),
                None => "None".into(),
            };
            writeln!(
                o,
                "    let t_{0} = {0}::template::<D>(scope, {parent}, &options);\n    st.set_template(ids::{1}, scope, t_{0});",
                self.traits[&ip.name].file,
                upper(&ip.name)
            )
            .unwrap();
        }
        o.push_str("    st\n}\n\n");

        // The security check of the interfaces a Window or Location can be `this` of.
        o.push_str("/// Web IDL \"perform a security check\" (§3.7.6) for a member of the interface `LO` that is not a\n/// cross-origin one: false, with a `SecurityError` thrown, when `this` is a Window or Location the\n/// current realm may not touch. Folds to nothing for the other interfaces.\n#[inline(always)]\npub(crate) fn security_check<const LO: u16>(scope: &mut v8::PinScope<'_, '_>, this: v8::Local<v8::Object>) -> bool {\n    if LO == ids::WINDOW {\n        rt::window_security_check(scope, this)\n    } else if LO == ids::LOCATION {\n        rt::location_security_check(scope, this)\n    } else if LO == ids::EVENT_TARGET {\n        rt::proto_id(&this) != ids::WINDOW || rt::window_security_check(scope, this)\n    } else {\n        true\n    }\n}\n\n");

        // The global templates.
        o.push_str("/// The kinds of realm the bindings install into, by their global object's interface.\n#[derive(Clone, Copy, Debug, PartialEq, Eq)]\npub enum GlobalKind {\n    /// A `Window` (`[Exposed=Window]`).\n    Window,\n    /// A `DedicatedWorkerGlobalScope` (`[Exposed=Worker]` and `[Exposed=DedicatedWorker]`).\n    DedicatedWorker,\n}\n\nimpl GlobalKind {\n    /// Whether an interface exposed in `names` (`*` for all) is exposed in this kind of realm.\n    pub fn exposes(self, names: &[&str]) -> bool {\n        names.iter().any(|n| match self {\n            GlobalKind::Window => *n == \"*\" || *n == \"Window\",\n            GlobalKind::DedicatedWorker => *n == \"*\" || *n == \"Worker\" || *n == \"DedicatedWorker\",\n        })\n    }\n}\n\n");
        let window = self.ifaces.iter().find(|i| i.global && i.name == "Window");
        let worker = self
            .ifaces
            .iter()
            .find(|i| i.global && i.name == "DedicatedWorkerGlobalScope");
        let id_of = |g: Option<&IfacePlan>| match g {
            Some(g) => format!("Some(ids::{})", upper(&g.name)),
            None => "None".into(),
        };
        writeln!(
            o,
            "/// The prototype id of the global object's interface for a kind of realm.\npub fn global_interface_id(kind: GlobalKind) -> Option<u16> {{\n    match kind {{\n        GlobalKind::Window => {},\n        GlobalKind::DedicatedWorker => {},\n    }}\n}}\n\n/// The object template of a realm's global object: the instance template of its `[Global]` interface, so\n/// the global object's prototype chain and members are the interface's.\npub fn global_template_for<'s>(scope: &v8::PinScope<'s, '_, ()>, kind: GlobalKind) -> Option<v8::Local<'s, v8::ObjectTemplate>> {{\n    let st = rt::state_of(scope)?;\n    Some(st.template(scope, global_interface_id(kind)?)?.instance_template(scope))\n}}\n\n/// [`global_template_for`] a Window.\npub fn global_template<'s>(scope: &v8::PinScope<'s, '_, ()>) -> Option<v8::Local<'s, v8::ObjectTemplate>> {{\n    global_template_for(scope, GlobalKind::Window)\n}}\n",
            id_of(window),
            id_of(worker)
        )
        .unwrap();
        if let Some(g) = window {
            writeln!(
                o,
                "/// The prototype id of a Window realm's global object's interface.\npub const GLOBAL_INTERFACE: InterfaceId = InterfaceId::{};\n",
                g.name
            )
            .unwrap();
        }

        // install_context: the interface objects on a realm's global.
        o.push_str("/// Installs the bindings in the current context of `scope`, whose isolate went through [`init_isolate`]:\n/// exposes the interface objects, namespace objects and legacy callback interface objects on the global\n/// object. When the context was made from [`global_template`], `global` is the engine's handle of the\n/// global object, stored in both the global proxy and the global object so members of the `[Global]`\n/// interface find their receiver.\npub fn install_context<D: Dom>(scope: &mut v8::PinScope<'_, '_>, global_handle: Option<rt::Handle>) -> Option<()> {\n    install_context_for::<D>(scope, global_handle, GlobalKind::Window)\n}\n\n/// [`install_context`] for a kind of realm: only the interfaces exposed in its globals.\npub fn install_context_for<D: Dom>(scope: &mut v8::PinScope<'_, '_>, global_handle: Option<rt::Handle>, kind: GlobalKind) -> Option<()> {\n    let st = rt::state(scope);\n    let context = scope.get_current_context();\n    let global = context.global(scope);\n");
        o.push_str("    if let (Some(h), Some(gid)) = (global_handle, global_interface_id(kind)) {\n        rt::adopt_wrapper(scope, global, h, gid);\n        if let Some(inner) = global.get_prototype(scope).and_then(|p| v8::Local::<v8::Object>::try_from(p).ok()) {\n            if inner.internal_field_count() == rt::WRAPPER_FIELDS {\n                rt::init_wrapper(inner, h, gid);\n            }\n        }\n    }\n");
        for g in self
            .ifaces
            .iter()
            .filter(|i| i.global && i.named_getter.is_some())
        {
            writeln!(
                o,
                "    if let (Some(h), Some(ids::{0})) = (global_handle, global_interface_id(kind)) {{\n        rt::install_named_properties_object(scope, ids::{0}, global, h)?;\n    }}",
                upper(&g.name)
            )
            .unwrap();
        }
        for ip in &self.ifaces {
            let f = &self.traits[&ip.name].file;
            let names: Vec<String> = ip.exposure.iter().map(|n| lit(n)).collect();
            if ip.no_interface_object {
                // [LegacyNoInterfaceObject] (Web IDL §3.7.3): the prototype object exists for its
                // objects, but there is no interface object and no `constructor` property.
                writeln!(
                    o,
                    "    let f_{f} = st.template(scope, ids::{})?.get_function(scope)?;\n    if let Some(p) = f_{f}.get(scope, rt::name(scope, \"prototype\").into()).and_then(|p| v8::Local::<v8::Object>::try_from(p).ok()) {{\n        p.delete(scope, rt::name(scope, \"constructor\").into())?;\n    }}",
                    upper(&ip.name)
                )
                .unwrap();
                if let Some(p) = &ip.parent {
                    writeln!(
                        o,
                        "    f_{f}.set_prototype(scope, f_{}.into())?;",
                        self.traits[p].file
                    )
                    .unwrap();
                }
                continue;
            }
            writeln!(
                o,
                "    let f_{f} = st.template(scope, ids::{})?.get_function(scope)?;\n    if kind.exposes(&[{}]) {{\n        rt::expose(scope, global, {}, f_{f})?;\n    }}",
                upper(&ip.name),
                names.join(", "),
                lit(&ip.name)
            )
            .unwrap();
            if let Some(p) = &ip.parent {
                // The interface object's [[Prototype]] is the parent's interface object (Web IDL §3.7.1).
                writeln!(
                    o,
                    "    f_{f}.set_prototype(scope, f_{}.into())?;",
                    self.traits[p].file
                )
                .unwrap();
            }
            if !ip.unscopables.is_empty() {
                let names: Vec<String> = ip.unscopables.iter().map(|n| lit(n)).collect();
                writeln!(
                    o,
                    "    rt::unscopables(scope, f_{f}, &[{}])?;",
                    names.join(", ")
                )
                .unwrap();
            }
            if ip.async_iterable.is_some() {
                writeln!(
                    o,
                    "    rt::async_iterator_install(scope, ids::{}, f_{f})?;",
                    upper(&ip.name)
                )
                .unwrap();
            }
            if ip.pair_iterable.is_some() {
                writeln!(
                    o,
                    "    rt::pair_iterator_install(scope, ids::{}, f_{f})?;",
                    upper(&ip.name)
                )
                .unwrap();
            } else if ip.setlike.is_some() {
                writeln!(
                    o,
                    "    rt::pair_iterator_install_as(scope, ids::{}, f_{f}, \"values\")?;",
                    upper(&ip.name)
                )
                .unwrap();
            }
            for fac in &ip.factories {
                let len = fac
                    .overloads
                    .iter()
                    .map(|ov| {
                        ov.args
                            .iter()
                            .rposition(|a| !a.optional && !a.variadic)
                            .map(|i| i + 1)
                            .unwrap_or(0)
                    })
                    .min()
                    .unwrap_or(0);
                writeln!(
                    o,
                    "    if kind == GlobalKind::Window {{\n        // [LegacyFactoryFunction={0}]: its prototype property is the interface prototype object.\n        let t = rt::builder({f}::factory_{1}_callback::<D>).length({len}).build(scope);\n        t.set_class_name(rt::name(scope, {2}));\n        let func = t.get_function(scope)?;\n        let proto = f_{f}.get(scope, rt::name(scope, \"prototype\").into())?;\n        func.define_own_property(scope, rt::name(scope, \"prototype\").into(), proto, v8::PropertyAttribute::READ_ONLY | v8::PropertyAttribute::DONT_ENUM | v8::PropertyAttribute::DONT_DELETE)?;\n        rt::expose(scope, global, {2}, func)?;\n    }}",
                    fac.name,
                    snake(&fac.name),
                    lit(&fac.name)
                )
                .unwrap();
            }
        }
        // [LegacyWindowAlias] (Web IDL §3.7.1): more names for an interface object on a Window.
        for (alias, target) in &self.model.aliases {
            if alias == "WindowProxy" {
                continue;
            }
            let Some(ip) = self.ifaces.iter().find(|i| &i.name == target) else {
                continue;
            };
            writeln!(
                o,
                "    if kind == GlobalKind::Window {{
        rt::expose(scope, global, {}, f_{})?;
    }}",
                lit(alias),
                self.traits[&ip.name].file
            )
            .unwrap();
        }
        for ns in &self.namespaces {
            let f = &self.traits[&ns.name].file;
            let names: Vec<String> = ns.exposure.iter().map(|n| lit(n)).collect();
            writeln!(
                o,
                "    if kind.exposes(&[{2}]) {{\n        // The {0} namespace object (Web IDL §3.13.1): writable, configurable, not enumerable.\n        let ns = {f}::namespace_object::<D>(scope)?;\n        global.define_own_property(scope, rt::name(scope, {1}).into(), ns.into(), v8::PropertyAttribute::DONT_ENUM)?;\n    }}",
                ns.name,
                lit(&ns.name),
                names.join(", ")
            )
            .unwrap();
        }
        for cb in &self.callback_objects {
            writeln!(
                o,
                "    if kind == GlobalKind::Window {{\n        // The legacy callback interface object of {0} (Web IDL §3.10): a function that throws, with the\n        // interface's constants and no prototype property.\n        let t = v8::FunctionTemplate::builder(rt::illegal_constructor).length(0).build(scope);\n        t.set_class_name(rt::name(scope, {1}));\n        t.remove_prototype();\n        let func = t.get_function(scope)?;",
                cb.name,
                lit(&cb.name)
            )
            .unwrap();
            for c in &cb.consts {
                let value = match &c.value {
                    Literal::Integer(_) => {
                        let v = c.value.integer_value().unwrap();
                        format!("v8::Number::new(scope, {v}.0).into()")
                    }
                    Literal::Bool(b) => format!("v8::Boolean::new(scope, {b}).into()"),
                    _ => continue,
                };
                writeln!(
                    o,
                    "        func.define_own_property(scope, rt::name(scope, {}).into(), {value}, v8::PropertyAttribute::READ_ONLY | v8::PropertyAttribute::DONT_DELETE)?;",
                    lit(&c.name)
                )
                .unwrap();
            }
            writeln!(
                o,
                "        rt::expose(scope, global, {}, func)?;\n    }}",
                lit(&cb.name)
            )
            .unwrap();
        }
        if self.ids.contains_key("DOMException") {
            o.push_str("    {\n        // The DOMException interface prototype object's [[Prototype]] is %Error.prototype% (Web IDL §3.14.1).\n        let error = global.get(scope, rt::name(scope, \"Error\").into())?;\n        let error: v8::Local<v8::Object> = error.try_into().ok()?;\n        let error_proto = error.get(scope, rt::name(scope, \"prototype\").into())?;\n        let proto = f_dom_exception.get(scope, rt::name(scope, \"prototype\").into())?;\n        let proto: v8::Local<v8::Object> = proto.try_into().ok()?;\n        proto.set_prototype(scope, error_proto)?;\n    }\n");
        }
        o.push_str("    Some(())\n}\n\n");
        o.push_str("/// [`init_isolate`] and [`install_context`] in one, for a context made without the global template\n/// (tests, tools): the interface objects are exposed on whatever global the context has.\npub fn install<D: Dom>(scope: &mut v8::PinScope<'_, '_>, engine: Rc<D>, options: rt::InstallOptions) -> Option<()> {\n    init_isolate(scope, engine, options);\n    install_context::<D>(scope, None)\n}\n");
        o
    }
}
